// Pins the Strip tool footers workflow (.github/workflows/strip-tool-footers.yml): what its
// regexes remove and what they leave, and the properties that make it safe to run with a write
// token on text anyone can post. The workflow never checks out code, so it cannot import a module
// from this repository; these tests read its script out of the workflow file instead, and so test
// exactly what runs.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripToolFooter } from '../scripts/check-attribution.mjs';

const workflow = readFileSync(new URL('../.github/workflows/strip-tool-footers.yml', import.meta.url), 'utf8');
const attributionWorkflow = readFileSync(new URL('../.github/workflows/attribution.yml', import.meta.url), 'utf8');

// The FOOTERS regexes and strip() exactly as the workflow's script declares them.
function workflowStrip() {
  const start = workflow.indexOf('const FOOTERS = [');
  const end = workflow.indexOf('const { owner, repo }');
  assert.ok(start !== -1 && end > start, 'the workflow declares FOOTERS and strip() before using them');
  return new Function(`${workflow.slice(start, end)}\nreturn { FOOTERS, strip };`)();
}

const { FOOTERS, strip } = workflowStrip();

// Exactly how the session tooling ends a comment, as seen on #404 and the other twelve.
const toolingFooter = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

test('the workflow declares the same three footer patterns as Green Light', () => {
  assert.deepEqual(FOOTERS.map(String), [
    String(/\n*[ \t]*-{3,}[ \t]*\n+[ \t]*_?Generated (?:by|with) \[Claude Code\]\([^)\n]*\)_?[ \t]*(?=\n|$)/gi),
    String(/\n*[ \t]*(?:🤖[ \t]*)?_?Generated (?:by|with) \[Claude Code\]\([^)\n]*\)_?[ \t]*(?=\n|$)/gi),
    String(/\n*[ \t]*<?https:\/\/claude\.ai\/code\/session_[A-Za-z0-9]+>?[ \t]*(?=\n|$)/g),
  ]);
});

test('a footer is removed and the text above it is kept as written', () => {
  const body = '**What changed**\n\n- One row, the same everywhere.\n\nLeaving this open for you to close.';
  assert.equal(strip(`${body}${toolingFooter}`), body);
  assert.equal(strip(`${body}${toolingFooter}\n`), body);
  assert.equal(strip(`${body}\n\n---\n\n_Generated by [Claude Code](https://claude.ai/code/session_01AbCdEf)_`), body);
  assert.equal(strip(`${body}\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)`), body);
  assert.equal(strip(`${body}\n\nhttps://claude.ai/code/session_01AbCdEf`), body);
  assert.equal(strip(`${body}\n\n<https://claude.ai/code/session_01AbCdEf>\n`), body);
});

test('stripping twice changes nothing more', () => {
  const once = strip(`Text.${toolingFooter}`);
  assert.equal(strip(once), once);
});

test('ordinary text is left alone, character for character', () => {
  for (const text of [
    'Plain comment.',
    'Trailing spaces and a newline stay.  \n',
    'The schema is generated by the migration script.',
    'No "Generated with ..." footer, per CLAUDE.md.',
    '',
  ]) {
    assert.equal(strip(text), text);
  }
  assert.equal(strip(undefined), undefined);
  assert.equal(strip(null), null);
});

test('a normal "---" rule is left alone', () => {
  for (const text of [
    'Above the rule.\n\n---\n\nBelow the rule.',
    'A rule that ends the comment.\n\n---',
    'A rule before a signature.\n\n---\n_Written by the owner_',
    '| a | b |\n|---|---|\n| 1 | 2 |',
  ]) {
    assert.equal(strip(text), text);
  }
});

test('a link to claude.ai that is not a footer is left alone', () => {
  for (const text of [
    'The docs are at https://claude.ai/code and say so.',
    'See [Claude Code](https://claude.ai/code) for what the session tooling is.',
    'https://claude.ai/code',
    'The run is at https://claude.ai/code/session_01AbCdEf if you want it.',
    'Discussed in https://claude.ai/code/session_01AbCdEf, then dropped.',
  ]) {
    assert.equal(strip(text), text);
  }
});

test('the workflow and the Attribution check strip the tooling footer to the same text', () => {
  // Both can clean a PR body (Attribution on PR events, this workflow when run by hand), so the
  // footer the tooling actually writes must come out the same either way.
  const body = '## What changed\n\nA real paragraph.\n\n---\n\nA rule the author drew.';
  for (const footer of [
    toolingFooter,
    '\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01AbCdEf)_\n',
    '\n\nhttps://claude.ai/code/session_01AbCdEf\n',
  ]) {
    assert.equal(strip(`${body}${footer}`), body);
    assert.equal(stripToolFooter(`${body}${footer}`), body);
  }
});

test('the workflow never checks out code and never runs text', () => {
  assert.doesNotMatch(workflow, /actions\/checkout/);
  assert.doesNotMatch(workflow, /^\s*(?:-\s*)?run:/m);
  // Payload text reaches the script only as data through context.payload, never interpolated into it.
  const script = workflow.slice(workflow.indexOf('script: |'));
  assert.doesNotMatch(script, /\$\{\{/);
  assert.doesNotMatch(script, /\beval\b|new Function|child_process|exec\(/);
  // Its one step is github-script, pinned to a full commit like every other action here.
  const uses = [...workflow.matchAll(/^\s*-?\s*uses:\s*(\S+)/gm)].map((match) => match[1]);
  assert.deepEqual(uses, ['actions/github-script@f28e40c7f34bde8b3046d885e986cb6290c5673b']);
});

test('the workflow edits only bodies, with the default token and nothing broader', () => {
  assert.match(workflow, /^permissions:\n  contents: read\n  issues: write\n  pull-requests: write\n\n/m);
  assert.doesNotMatch(workflow, /secrets\./);
  const calls = [...workflow.matchAll(/github\.rest\.(\w+\.\w+)\(/g)].map((match) => match[1]);
  assert.deepEqual([...new Set(calls)].sort(), [
    'issues.update', 'issues.updateComment', 'pulls.updateReview', 'pulls.updateReviewComment',
  ]);
  for (const call of workflow.matchAll(/github\.rest\.\w+\.update\w*\(\{([^}]*)\}\)/g)) {
    assert.match(call[1], /\bbody\b/);
    assert.doesNotMatch(call[1], /\b(?:title|state|labels|assignees|event)\b/);
  }
});

test('the workflow runs on what people post, and by hand, but leaves PR events to Attribution', () => {
  const on = workflow.slice(workflow.indexOf('\non:\n'), workflow.indexOf('\npermissions:'));
  for (const trigger of [
    'issues:\n    types: [opened, edited]',
    'issue_comment:\n    types: [created, edited]',
    'pull_request_review:\n    types: [submitted, edited]',
    'pull_request_review_comment:\n    types: [created, edited]',
    'workflow_dispatch:',
  ]) {
    assert.ok(on.includes(trigger), trigger);
  }
  assert.doesNotMatch(on, /^\s*pull_request(?:_target)?:/m);
  // Attribution still removes the footer from a PR body, then checks everything it always did.
  assert.match(attributionWorkflow, /node scripts\/check-attribution\.mjs --strip-pr-body/);
  assert.match(attributionWorkflow, /- run: node scripts\/check-attribution\.mjs\n/);
  assert.match(attributionWorkflow, /pull_request:\n    types: \[opened, edited, reopened, synchronize\]/);
});
